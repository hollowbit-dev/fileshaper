import { _electron as electron } from 'playwright';
import path from 'path';
const app = await electron.launch({ args: [path.resolve('.'), '--user-data-dir=/tmp/fs-motion'] });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1200, height: 760 });
await page.waitForSelector('.cmd');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.evaluate(() => window.fileshaper.setSettings({ outDir: '/tmp', theme: 'dark' }));
await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
await page.evaluate((f) => window.__fileshaperTest.addFiles(f), [path.resolve('test/demo/IMG_4821.HEIC'), path.resolve('test/demo/Wallpaper.jpg')]);
await page.waitForSelector('.qitem');
const ind = async () => page.$eval('#seg .seg-ind', (n) => n.style.transform + ' w=' + n.style.width);
console.log('seg start', await ind());
await page.click('[data-act="resize"]'); await page.waitForTimeout(60);
console.log('seg mid  ', await page.$eval('#seg .seg-ind', (n) => getComputedStyle(n).transform));
await page.waitForTimeout(400);
console.log('seg end  ', await ind(), 'button at', await page.$eval('[data-act="resize"]', (n) => n.offsetLeft));
await page.click('[data-act="convert"]'); await page.waitForTimeout(400);
await page.click('#run');
await page.waitForSelector('.qitem.just-done', { timeout: 30000 });
await page.waitForTimeout(250);
await page.screenshot({ path: 'test/shots/app-done.png', clip: { x: 220, y: 0, width: 980, height: 400 } });
await page.waitForTimeout(1500);
console.log('rm buttons back:', await page.$$eval('[data-rm]', (n) => n.length), 'errors', errs);
await page.keyboard.press('Meta+K'); await page.waitForTimeout(80);
await page.screenshot({ path: 'test/shots/app-palette.png' });
await app.close();
